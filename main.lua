-- Archaeology Tracker: tracks artifacts, collections, materials and relics.

local log = require("core/log")
local storage = require("core/storage")
local progress = require("core/progress")
local catalog = require("core/catalog")
local restore = require("core/restore")
local artifactsWindow = require("windows/artifacts_window")
local artifactDetail = require("windows/artifact_detail")
local collectionsWindow = require("windows/collections_window")
local collectionDetail = require("windows/collection_detail")
local materialsWindow = require("windows/materials_window")
local materialDetail = require("windows/material_detail")
local hotspotDetail = require("windows/hotspot_detail")
local relicPowersWindow = require("windows/relic_powers_window")
local relicPowerDetail = require("windows/relic_power_detail")
local relicDetail = require("windows/relic_detail")
local restoreTracker = require("core/restoration_tracker")
local restoreTrackerWindow = require("windows/restoration_tracker_window")
local overviewWindow = require("windows/overview_window")
local pinnedNeeds = require("windows/pinned_needs_window")
local clock = require("core/clock")
local researchTeam = require("core/research_team")
local tracking = require("tracking/tracking")
local chronotes = require("core/chronotes")
local launcher = require("windows/launcher")

log.enabled = false  -- set to true to show and save test messages (read them with tools/read_plugin_output.py)
log.start()
storage.start()
catalog.start()
restore.start()
tracking.start()
chronotes.start()
artifactsWindow.start()
artifactDetail.start()
collectionsWindow.start()
collectionDetail.start()
materialsWindow.start()
materialDetail.start()
hotspotDetail.start()
relicPowersWindow.start()
relicPowerDetail.start()
relicDetail.start()
restoreTracker.start()
restoreTrackerWindow.start()
clock.start()
researchTeam.start()
overviewWindow.start()
pinnedNeeds.start()
launcher.start()

log.say("Loaded. Archaeology level " .. tostring(progress.level()))

-- The game calls this when the plugin is turned off or the client closes.
function PluginShutdown()
    launcher.remove()
    storage.save()
    log.save()
end
